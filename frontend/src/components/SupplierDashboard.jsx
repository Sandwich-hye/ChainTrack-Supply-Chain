import React, { useEffect, useState } from 'react';
import TransactionForm from './TransactionForm';
import { generateProductId } from '../services/contractService';

export default function SupplierDashboard({address,refreshProduct,contextKey}) {
  const [productId,setProductId] = useState('');
  const [generating,setGenerating] = useState(true);
  useEffect(() => { let alive = true; setProductId(''); setGenerating(true); generateProductId().then(id => { if (!alive) return; setProductId(id.toString()); setGenerating(false); }).catch(() => { if (!alive) return; setProductId('Unavailable'); setGenerating(false); }); return () => { alive = false; }; },[contextKey]);
  const create = async () => {
    if (productId === 'Unavailable') throw new Error('Product ID generation unavailable. Refresh and try again.');
    const result = await refreshProduct(productId,contextKey);
    return result;
  };
  return <section className="dashboard"><p className="eyebrow">Clothing supplier</p><h2>Create clothing product</h2><p className="muted">Register a new clothing shipment for the supply chain.</p>
    <TransactionForm address={address} title="Create Product" description="Product ID is generated by this application and checked against the configured contract." method="createProduct" disabled={generating || productId === 'Unavailable'} generatedFields={[{label:'Product ID (automatic)',value:generating ? 'Generating…' : productId}]} fields={[{name:'name',label:'Product Name',placeholder:'Classic Cotton T-Shirt'},{name:'quantity',label:'Quantity',type:'uint',positive:true,min:1,step:1}]} prepare={args => [BigInt(productId),...args]} onSuccess={create}/>
  </section>;
}
